package postgres

import (
	"context"
	"fmt"
	"strings"

	"github.com/jackc/pgx/v5/pgxpool"

	"lotustab/internal/core/driver"
	"lotustab/internal/drivers/sqlutil"
)

func (c *conn) DescribeTable(ctx context.Context, ref driver.TableRef) (*driver.TableStructure, error) {
	ref = driver.ClampTableRef(ref)
	if ref.Name == "" {
		return nil, fmt.Errorf("table name is required")
	}
	pool, cleanup, err := c.poolFor(ctx, ref.Database)
	if err != nil {
		return nil, err
	}
	defer cleanup()

	cols, err := postgresDescribeColumns(ctx, pool, ref.Schema, ref.Name)
	if err != nil {
		return nil, err
	}
	pk, err := postgresPrimaryKey(ctx, pool, ref.Schema, ref.Name)
	if err != nil {
		return nil, err
	}
	pkSet := make(map[string]struct{}, len(pk))
	for _, name := range pk {
		pkSet[name] = struct{}{}
	}
	for i := range cols {
		if _, ok := pkSet[cols[i].Name]; ok {
			cols[i].IsPrimaryKey = true
		}
	}
	return &driver.TableStructure{Columns: cols, CanReorder: false}, nil
}

func (c *conn) AlterTable(ctx context.Context, req driver.AlterTableRequest) error {
	req = driver.ClampAlterTable(req)
	if req.Name == "" {
		return fmt.Errorf("table name is required")
	}
	if len(req.Ops) == 0 {
		return fmt.Errorf("no schema changes")
	}
	pool, cleanup, err := c.poolFor(ctx, req.Database)
	if err != nil {
		return err
	}
	defer cleanup()

	qualified := postgresQualified(req.Schema, req.Name)
	stmts, err := postgresAlterSQL(qualified, req.Ops)
	if err != nil {
		return err
	}

	tx, err := pool.Begin(ctx)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback(ctx) }()
	for _, stmt := range stmts {
		if _, err := tx.Exec(ctx, stmt); err != nil {
			return err
		}
	}
	return tx.Commit(ctx)
}

func postgresDescribeColumns(ctx context.Context, pool *pgxpool.Pool, schema, name string) ([]driver.ColumnInfo, error) {
	const q = `
		SELECT
			a.attname,
			format_type(a.atttypid, a.atttypmod),
			NOT a.attnotnull,
			pg_get_expr(ad.adbin, ad.adrelid),
			COALESCE(a.attidentity, '') <> ''
				OR pg_get_serial_sequence(quote_ident(n.nspname) || '.' || quote_ident(c.relname), a.attname) IS NOT NULL,
			COALESCE(a.attidentity, ''),
			COALESCE(col_description(c.oid, a.attnum), ''),
			a.attnum
		FROM pg_attribute a
		JOIN pg_class c ON c.oid = a.attrelid
		JOIN pg_namespace n ON n.oid = c.relnamespace
		LEFT JOIN pg_attrdef ad ON ad.adrelid = c.oid AND ad.adnum = a.attnum
		WHERE n.nspname = CASE WHEN $1 = '' THEN current_schema() ELSE $1 END
		  AND c.relname = $2
		  AND a.attnum > 0
		  AND NOT a.attisdropped
		ORDER BY a.attnum`
	rows, err := pool.Query(ctx, q, schema, name)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	out := make([]driver.ColumnInfo, 0)
	ordinal := 0
	for rows.Next() {
		var (
			colName, colType, attIdentity, comment string
			nullable, autoInc                      bool
			def                                    *string
			attnum                                 int
		)
		if err := rows.Scan(&colName, &colType, &nullable, &def, &autoInc, &attIdentity, &comment, &attnum); err != nil {
			return nil, err
		}
		ordinal++
		info := driver.ColumnInfo{
			Name:          colName,
			Type:          colType,
			Nullable:      nullable,
			AutoIncrement: autoInc,
			Extra:         postgresExtra(attIdentity, autoInc),
			Comment:       comment,
			Ordinal:       ordinal,
		}
		if def != nil {
			s := *def
			info.Default = &s
		}
		out = append(out, info)
	}
	if err := rows.Err(); err != nil {
		return nil, err
	}
	return out, nil
}

func postgresExtra(attIdentity string, autoInc bool) string {
	switch attIdentity {
	case "d":
		return "GENERATED BY DEFAULT AS IDENTITY"
	case "a":
		return "GENERATED ALWAYS AS IDENTITY"
	}
	if autoInc {
		return "auto_increment"
	}
	return ""
}

func postgresAlterSQL(qualified string, ops []driver.ColumnOp) ([]string, error) {
	if len(ops) == 0 {
		return nil, fmt.Errorf("no schema changes")
	}
	out := make([]string, 0)
	for i, op := range ops {
		stmts, err := postgresAlterStmts(qualified, op)
		if err != nil {
			return nil, fmt.Errorf("op %d: %w", i, err)
		}
		out = append(out, stmts...)
	}
	return out, nil
}

func postgresAlterStmts(qualified string, op driver.ColumnOp) ([]string, error) {
	q := sqlutil.QuotePostgres
	switch op.Kind {
	case driver.ColumnOpDrop:
		if op.Name == "" {
			return nil, fmt.Errorf("drop requires a column name")
		}
		return []string{"ALTER TABLE " + qualified + " DROP COLUMN " + q(op.Name)}, nil
	case driver.ColumnOpAdd:
		if op.Column == nil {
			return nil, fmt.Errorf("add requires a column definition")
		}
		def, err := postgresColumnDef(*op.Column)
		if err != nil {
			return nil, err
		}
		stmts := []string{"ALTER TABLE " + qualified + " ADD COLUMN " + def}
		if op.Column.Comment != "" {
			stmts = append(stmts, postgresCommentSQL(qualified, op.Column.Name, op.Column.Comment))
		}
		return stmts, nil
	case driver.ColumnOpModify:
		if op.Column == nil {
			return nil, fmt.Errorf("modify requires a column definition")
		}
		oldName := op.Name
		if oldName == "" {
			oldName = op.Column.Name
		}
		if oldName == "" {
			return nil, fmt.Errorf("modify requires a column name")
		}
		return postgresModifyStmts(qualified, oldName, *op.Column), nil
	case driver.ColumnOpReorder:
		return nil, fmt.Errorf("column reorder is not supported on PostgreSQL")
	default:
		return nil, fmt.Errorf("unknown alter op %q", op.Kind)
	}
}

func postgresModifyStmts(qualified, oldName string, col driver.ColumnInfo) []string {
	q := sqlutil.QuotePostgres
	current := oldName
	stmts := make([]string, 0, 4)
	newName := col.Name
	if newName == "" {
		newName = oldName
	}
	if newName != oldName {
		stmts = append(stmts, "ALTER TABLE "+qualified+" RENAME COLUMN "+q(oldName)+" TO "+q(newName))
		current = newName
	}
	if col.Type != "" {
		quoted := q(current)
		stmts = append(stmts, "ALTER TABLE "+qualified+" ALTER COLUMN "+quoted+" TYPE "+col.Type+" USING "+quoted+"::"+col.Type)
	}
	if col.Nullable {
		stmts = append(stmts, "ALTER TABLE "+qualified+" ALTER COLUMN "+q(current)+" DROP NOT NULL")
	} else {
		stmts = append(stmts, "ALTER TABLE "+qualified+" ALTER COLUMN "+q(current)+" SET NOT NULL")
	}
	if col.Default == nil {
		stmts = append(stmts, "ALTER TABLE "+qualified+" ALTER COLUMN "+q(current)+" DROP DEFAULT")
	} else {
		def := sqlutil.FormatDefault(*col.Default)
		stmts = append(stmts, "ALTER TABLE "+qualified+" ALTER COLUMN "+q(current)+" SET DEFAULT "+def)
	}
	stmts = append(stmts, postgresCommentSQL(qualified, current, col.Comment))
	return stmts
}

func postgresCommentSQL(qualified, name, comment string) string {
	value := "NULL"
	if comment != "" {
		value = sqlutil.QuoteString(comment)
	}
	return "COMMENT ON COLUMN " + qualified + "." + sqlutil.QuotePostgres(name) + " IS " + value
}

func postgresColumnDef(col driver.ColumnInfo) (string, error) {
	if col.Name == "" {
		return "", fmt.Errorf("column name is required")
	}
	if col.Type == "" {
		return "", fmt.Errorf("column type is required")
	}
	var b strings.Builder
	b.WriteString(sqlutil.QuotePostgres(col.Name))
	b.WriteByte(' ')
	b.WriteString(col.Type)
	if !col.Nullable {
		b.WriteString(" NOT NULL")
	}
	if col.Default != nil {
		b.WriteString(" DEFAULT ")
		b.WriteString(sqlutil.FormatDefault(*col.Default))
	}
	if col.AutoIncrement {
		b.WriteString(" GENERATED BY DEFAULT AS IDENTITY")
	}
	return b.String(), nil
}
