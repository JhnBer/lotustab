func TestSearchTablesEmpty(t *testing.T) {
	c := &conn{}
	got, err := c.SearchTables(context.Background(), "", "  ", 10)
	if err != nil {
		t.Fatal(err)
	}
	if got == nil || len(got) != 0 {
		t.Fatalf("empty query should not hit the server, got %v", got)
	}
}

func TestPostgresAlterSQL(t *testing.T) {
	def := "guest"
	stmts, err := postgresAlterSQL(`"public"."users"`, []driver.ColumnOp{
		{Kind: driver.ColumnOpDrop, Name: "legacy"},
		{Kind: driver.ColumnOpAdd, Column: &driver.ColumnInfo{Name: "nickname", Type: "varchar(64)", Nullable: false, Default: &def}},
		{Kind: driver.ColumnOpModify, Name: "name", Column: &driver.ColumnInfo{Name: "full_name", Type: "text", Nullable: true}},
	})
	if err != nil {
		t.Fatal(err)
	}
	joined := strings.Join(stmts, "; ")
	want := []string{
		`ALTER TABLE "public"."users" DROP COLUMN "legacy"`,
		`ALTER TABLE "public"."users" ADD COLUMN "nickname" varchar(64) NOT NULL DEFAULT 'guest'`,
		`ALTER TABLE "public"."users" RENAME COLUMN "name" TO "full_name"`,
		`ALTER TABLE "public"."users" ALTER COLUMN "full_name" TYPE text USING "full_name"::text`,
		`ALTER TABLE "public"."users" ALTER COLUMN "full_name" DROP NOT NULL`,
		`ALTER TABLE "public"."users" ALTER COLUMN "full_name" DROP DEFAULT`,
		`COMMENT ON COLUMN "public"."users"."full_name" IS NULL`,
	}
	for _, part := range want {
		if !strings.Contains(joined, part) {
			t.Fatalf("missing %q in %s", part, joined)
		}
	}
}

func TestPostgresAlterSQLRejectsReorder(t *testing.T) {
	_, err := postgresAlterSQL(`"t"`, []driver.ColumnOp{
		{Kind: driver.ColumnOpReorder, Name: "id", Column: &driver.ColumnInfo{Name: "id", Type: "int"}},
	})
	if err == nil || !strings.Contains(err.Error(), "not supported") {
		t.Fatalf("expected reorder error, got %v", err)
	}
}

func TestPostgresExtra(t *testing.T) {
	tests := []struct {
		attIdentity string
		autoInc     bool
		want        string
	}{
		{attIdentity: "d", autoInc: true, want: "GENERATED BY DEFAULT AS IDENTITY"},
		{attIdentity: "a", autoInc: true, want: "GENERATED ALWAYS AS IDENTITY"},
		{attIdentity: "", autoInc: true, want: "auto_increment"},
		{attIdentity: "", autoInc: false, want: ""},
	}
	for _, tt := range tests {
		if got := postgresExtra(tt.attIdentity, tt.autoInc); got != tt.want {
			t.Errorf("postgresExtra(%q, %v) = %q, want %q", tt.attIdentity, tt.autoInc, got, tt.want)
		}
	}
}

func TestPostgresCreateSQL(t *testing.T) {
	def := "now()"
	got, err := postgresCreateSQL(`"public"."users"`, []driver.ColumnInfo{
		{Name: "id", Type: "integer", Nullable: false, AutoIncrement: true, Extra: "GENERATED ALWAYS AS IDENTITY"},
		{Name: "name", Type: "text", Nullable: true, Default: &def},
	}, []string{"id"})
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		`CREATE TABLE "public"."users" (`,
		`"id" integer GENERATED ALWAYS AS IDENTITY NOT NULL`,
		`"name" text DEFAULT now()`,
		`PRIMARY KEY ("id")`,
	}
	for _, part := range want {
		if !strings.Contains(got, part) {
			t.Fatalf("missing %q in %s", part, got)
		}
	}
}
