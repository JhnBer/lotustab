func (c *conn) StreamTable(ctx context.Context, req driver.StreamTableRequest, fn func(cols []driver.Column, rows [][]any) error) error {
	req = driver.ClampStreamTable(req)
	if req.Name == "" {
		return fmt.Errorf("table name is required")
	}
	if fn == nil {
		return fmt.Errorf("stream callback is required")
	}
	pool, cleanup, err := c.poolFor(ctx, req.Database)
	if err != nil {
		return err
	}
	defer cleanup()

	qualified := postgresQualified(req.Schema, req.Name)
	query := sqlutil.SelectStar(qualified, req.WhereSQL)
	log.Printf("export stream: %s", query)

	tx, err := pool.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.RepeatableRead})
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback(ctx) }()

	if err := streamPool(ctx, tx, query, nil, fn); err != nil {
		return err
	}
	return tx.Commit(ctx)
}

func (c *conn) TableDDL(ctx context.Context, ref driver.TableRef) (string, error) {
	ref = driver.ClampTableRef(ref)
	if ref.Name == "" {
		return "", fmt.Errorf("table name is required")
	}
	pool, cleanup, err := c.poolFor(ctx, ref.Database)
	if err != nil {
		return "", err
	}
	defer cleanup()

	cols, err := postgresDescribeColumns(ctx, pool, ref.Schema, ref.Name)
	if err != nil {
		return "", err
	}
	if len(cols) == 0 {
		return "", fmt.Errorf("table not found")
	}
	pk, err := postgresPrimaryKey(ctx, pool, ref.Schema, ref.Name)
	if err != nil {
		return "", err
	}
	return postgresCreateSQL(postgresQualified(ref.Schema, ref.Name), cols, pk)
}

type pgxQuerier interface {
	Query(ctx context.Context, sql string, args ...any) (pgx.Rows, error)
}

func streamPool(ctx context.Context, q pgxQuerier, sqlText string, args []any, fn func(cols []driver.Column, rows [][]any) error) error {
	rows, err := q.Query(ctx, sqlText, args...)
	if err != nil {
		return err
	}
	defer rows.Close()

	fields := rows.FieldDescriptions()
	columns := make([]driver.Column, len(fields))
	for i, f := range fields {
		columns[i] = driver.Column{Name: f.Name, Type: typeName(f.DataTypeOID)}
	}

	batch := make([][]any, 0, streamBatchSize)
	sent := false
	flush := func() error {
		if len(batch) == 0 {
			return nil
		}
		sent = true
		err := fn(columns, batch)
		batch = make([][]any, 0, streamBatchSize)
		return err
	}
	for rows.Next() {
		values, err := rows.Values()
		if err != nil {
			return err
		}
		row := make([]any, len(values))
		copy(row, values)
		batch = append(batch, row)
		if len(batch) >= streamBatchSize {
			if err := flush(); err != nil {
				return err
			}
		}
	}
	if err := rows.Err(); err != nil {
		return err
	}
	if err := flush(); err != nil {
		return err
	}
	if !sent {
		return fn(columns, nil)
	}
	return nil
}

const streamBatchSize = 1000

func postgresCreateSQL(qualified string, cols []driver.ColumnInfo, pk []string) (string, error) {
	if len(cols) == 0 {
		return "", fmt.Errorf("no columns")
	}
	var b strings.Builder
	b.WriteString("CREATE TABLE ")
	b.WriteString(qualified)
	b.WriteString(" (\n")
	for i, col := range cols {
		def, err := postgresDumpColumnDef(col)
		if err != nil {
			return "", err
		}
		if i > 0 {
			b.WriteString(",\n")
		}
		b.WriteString("  ")
		b.WriteString(def)
	}
	if len(pk) > 0 {
		b.WriteString(",\n  PRIMARY KEY (")
		for i, name := range pk {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(sqlutil.QuotePostgres(name))
		}
		b.WriteString(")")
	}
	b.WriteString("\n);")
	return b.String(), nil
}

func postgresDumpColumnDef(col driver.ColumnInfo) (string, error) {
	if col.Name == "" {
		return "", fmt.Errorf("column name is required")
	}
	if col.Type == "" {
		return "", fmt.Errorf("column type is required")
	}
	var b strings.Builder
	b.WriteString(sqlutil.QuotePostgres(col.Name))
	b.WriteByte(' ')
	b.WriteString(col.Type)
	if strings.Contains(strings.ToUpper(col.Extra), "GENERATED") {
		b.WriteByte(' ')
		b.WriteString(col.Extra)
	} else if col.AutoIncrement {
		b.WriteString(" GENERATED BY DEFAULT AS IDENTITY")
	}
	if !col.Nullable {
		b.WriteString(" NOT NULL")
	}
	if col.Default != nil && !strings.Contains(strings.ToUpper(col.Extra), "GENERATED") {
		b.WriteString(" DEFAULT ")
		b.WriteString(sqlutil.FormatDefault(*col.Default))
	}
	return b.String(), nil
}

